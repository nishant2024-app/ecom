import { useEffect, useState } from 'react';
import { api, tomorrowIST } from '../lib/api';

interface Plan {
  date: string;
  generatedAt: string | null;
  lines: { variantId: string; name: string; required: number; buffer: number; inStock: number; toProduce: number }[];
}

export function ProductionPage() {
  const [date, setDate] = useState(tomorrowIST());
  const [slotId, setSlotId] = useState('');
  const [plan, setPlan] = useState<Plan | null>(null);

  useEffect(() => {
    api<{ data: { id: string }[] }>('/v1/admin/slots').then((r) => setSlotId(r.data[0]?.id ?? ''));
  }, []);
  useEffect(() => {
    if (slotId) api<Plan>(`/v1/admin/production-plan?date=${date}&slotId=${slotId}`).then(setPlan);
  }, [date, slotId]);

  return (
    <div className="p-6">
      <header className="flex items-end justify-between rule-b pb-4">
        <div>
          <h1 className="font-display text-2xl">Production plan</h1>
          <p className="text-ink-2">
            {plan?.generatedAt ? `Generated ${new Date(plan.generatedAt).toLocaleString('en-IN', { timeZone: 'Asia/Kolkata' })}` : 'Generated by the cutoff job'}
          </p>
        </div>
        <label className="text-xs text-ink-2">
          Delivery date
          <input type="date" value={date} onChange={(e) => setDate(e.target.value)} className="num mt-1 block h-9 rounded-1 border border-rule bg-paper px-2 text-ink" />
        </label>
      </header>
      <table className="mt-6 w-full max-w-3xl border-collapse text-left">
        <thead>
          <tr className="text-xs uppercase tracking-[0.1em] text-ink-2 rule-b">
            <th className="py-2 pr-4 font-normal">Product</th>
            <th className="py-2 pr-4 text-right font-normal">Required</th>
            <th className="py-2 pr-4 text-right font-normal">Buffer 5%</th>
            <th className="py-2 pr-4 text-right font-normal">In stock</th>
            <th className="py-2 text-right font-normal">To produce</th>
          </tr>
        </thead>
        <tbody>
          {plan?.lines.map((l) => (
            <tr key={l.variantId} className="rule-b">
              <td className="py-2 pr-4">{l.name}</td>
              <td className="num py-2 pr-4 text-right">{l.required}</td>
              <td className="num py-2 pr-4 text-right text-ink-2">{l.buffer}</td>
              <td className="num py-2 pr-4 text-right text-ink-2">{l.inStock}</td>
              <td className="num py-2 text-right text-lg">{l.toProduce}</td>
            </tr>
          ))}
          {plan && plan.lines.length === 0 && (
            <tr>
              <td colSpan={5} className="py-6 text-ink-2">
                No plan for this date yet. It appears after the cutoff job runs.
              </td>
            </tr>
          )}
        </tbody>
      </table>
    </div>
  );
}
